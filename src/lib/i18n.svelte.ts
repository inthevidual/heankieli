export type UiLang = "en" | "sv";
export type Key = keyof Dict;

const dicts: Record<UiLang, Dict> = { en, sv };

let current = $state<UiLang>("en");

export function setUiLang(l: UiLang) {
  current = l;
  document.documentElement.lang = l;
}

export function uiLang(): UiLang {
  return current;
}

/** Swedish (and Finnish/Meänkieli speakers in Sweden often use Swedish) gets Swedish, others English. */
export function langFromLocale(locale: string): UiLang {
  const l = locale.toLowerCase();
  return l.startsWith("sv") || l.startsWith("fit") ? "sv" : "en";
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = dicts[current][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
